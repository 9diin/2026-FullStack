// 2. 리액트란 무엇인가?
// 리액트는 사용자 인터페이스(UI)를 만들기 위한 자바스크립트 라이브러리입니다.
// 특히 화면이 자주 바뀌고, 데이터 상태(state)에 따라 UI가 동적으로 달라지는 웹 애플리케이션을 구조적으로 개발하는 데에 적합합니다.
// 리액트는 컴포넌트 기반 아키텍처를 사용하여 UI를 구성한다.

// 2.1 리액트가 왜 필요할까?
// "우리가 만드는 웹 페이지는 단순히 글을 보여주는 문서일까요? 아니면 사용자가가 상호작용할 수 있는 애플리케이션일까요?"
// 리액트는 후자에 해당하는 웹 애플리케이션을 만들기 위해 필요합니다.
// 로그인 여부에 따라 메뉴가 달라지기도 하며, 댓글이 추가되고, 좋아요 수가 바뀌는 등 이런 화면을 자바스크립트만으로 관리하려면 상당히 복잡한 로직이 필요합니다.

// - 로그인 전과 후에 헤더 메뉴는 어떻게 달라질까요?
// - 댓글이 추가되면 화면에 바로 반영될까요?
// - 장바구니에 상품을 추가하면 어떻 화면 요소가 함께 반영될까요?
// - 좋아요 수가 바뀌면 화면에 바로 반영될까요?
// - 데이터가 바뀔 때마다 개발자가 직접 HTML 요소를 찾아 수정한다면 어떤 문제가 발생할까요?

// 과거의 자바스크립트에서는 다음과 같은 순서로 화면을 수정했습니다.
// 1. 화면에 표시되는 데이터를 자바스크립트 변수에 저장합니다.
// 2. 화면에 표시되는 데이터를 바탕으로 HTML 요소를 생성합니다.
// 3. HTML 요소를 DOM에 추가합니다.
// 4. 데이터가 바뀌면, 변경된 데이터를 자바스크립트 변수에 저장합니다.
// 5. 변경된 데이터를 바탕으로 HTML 요소를 새로 생성합니다.
// 6. 기존 HTML 요소를 DOM에서 제거하고, 새로 생성한 HTML 요소를 DOM에 추가합니다.

// 위와 같은 방식은 화면이 복잡해질수록 코드가 길어지고, 유지보수가 어려워집니다.
// 또한, 데이터가 바뀔 때마다 전체 화면을 새로 렌더링하기 때문에 성능 저하가 발생할 수 있습니다.

// 리액트는 이러한 문제를 해결하기 위해 등장했습니다.
// 리액트는 데이터 상태(state)에 따라 UI를 자동으로 업데이트하고, 필요한 부분만 효율적으로 렌더링합니다.
// 이를 통해 개발자는 데이터와 UI를 분리하여 관리할 수 있으며, 코드의 가독성과 유지보수성을 높일 수 있습니다.

