// 1. SPA란 무엇인가?
// 웹 애플리케이션이 발전하기 이전에는 화면을 전환할 때마다 서버에서 새로운 페이지를 받아와야 했습니다.
// 버튼을 클릭할 때마다 화면이 깜박이고, 로딩 시간이 길어 사용자 경험이 떨어졌습니다.
// 이러한 한계를 해결하기 위해 등장한 방식이 SPA(Single Page Application)입니다.
// SPA는 이름 그대로 하나의 페이지에서 모든 화면 전환과 상화작용을 처리하는 애플리케이션 구조입니다.

// 1.1 SPA의 핵심 개념
// SPA는 초기 로딩 시 필요한 리소스(HTML, CSS, JavaScript)를 한 번에 받아오고,
// 그 이후부터는 페이지 전체가 아니라 바뀌는 부분만 동적으로 갱신하는 방식입니다.

// 즉, "필요한 UI만 업데이트하여 빠르고 부드럽게 동작하는 웹 애플리케이션 방식"이라고 정의할 수 있습니다.

// 이 방식이 가능한 이유는 컴포넌트(Component)라는 개념 덕분입니다.
// 컴포넌트는 화면을 여러 개의 작은 모듈로 나누어 재사용할 수 있는 단위입니다.
// 필요한 컴포넌트만 다시 렌더링하여 성능을 향상시킵니다.

// 1.2 SPA & MPA
// 페이지 구조: 하나의 HTML 페이지 / 요청마다 새로운 HTML 페이지를 받아오는 구조
// 렌더링 방식: CSR(Client Side Rendering) / SSR(Server Side Rendering)
// 화면 전환: 빠르고 부드러움 / 새로고침 & 깜박임 발생
// 요청 방식: 데이터만 요청 (JSON) / 전체 페이지 요청 (HTML)
// 대표 사례: React, Vue, Angular / 전통적인 웹사이트

// 1.3 SPA의 장점
// 1. 빠른 화면 전환: 필요한 부분만 업데이트하므로 전체 페이지를 다시 로드할 필요가 없습니다.
// 2. 부드러운 사용자 경험: 화면 깜박임이 없고, 애니메이션과 전환 효과를 자연스럽게 구현할 수 있습니다.
// 3. 효율적인 데이터 처리: 서버와의 통신을 최소화하여 불필요한 데이터 전송을 줄일 수 있습니다.
// 4. 개발 생산성 향상: 컴포넌트 기반 구조로 코드 재사용성이 높아지고 유지보수가 용이합니다.

// 1.4 SPA의 단점
// 1. 초기 로딩 시간: 초기 로딩 시 필요한 리소스를 한 번에 받아오기 때문에 초기 로딩 시간이 길어질 수 있습니다.
// 2. SEO(Search Engine Optimization) 문제: 검색 엔진이 JavaScript를 제대로 처리하지 못하면 SEO에 불리할 수 있습니다.
// 3. 복잡한 상태 관리: SPA는 클라이언트 측에서 상태를 관리해야 하므로, 상태 관리가 복잡해질 수 있습니다.

// 1.5 왜 SPA를 사용하는가?
// 현대 웹 애플리케이션은 단순 정보 제공이 아니라 검색, 입력, 메시지, 알림 등 풍부한 사용자 상호작용이 필수입니다.
// 따라서 페이지 전체를 매번 새로 불러오는 방식보다 화면 일부만 갱신하는 SPA 방식이 더 적합합니다.

