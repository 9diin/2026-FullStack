// 필요한 컴포넌트가 쉽게 접근하고 수정할 수 있도록 도와주는 도구

// [역할]
// - 전역(Global) 상태 저장소 제공 ✅
// - Props 전달 없이 상태 공유 가능 ✅
// - 상태 변경 시 필요한 컴포넌트만 자동 업데이트 ✅
// - 예측 가능한 데이터 흐름 유지 ✅

